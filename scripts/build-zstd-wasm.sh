#!/usr/bin/env bash
# Rebuilds packages/core/src/zstd-wasm.ts, the decoder-only zstd WebAssembly module that reads
# schema-2 package bodies (app on every platform, and the pipeline's round-trip check), and
# packages/core/src/zstd-js.ts, the same module translated to plain JavaScript by wasm2js for
# WebViews without WebAssembly (iOS Lockdown Mode).
set -euo pipefail
ZSTD_VERSION=1.5.7
ZSTD_SHA256=eb33e51f49a15e023950cd7825ca74a4a2b43db8354825ac24fc1b7ee09e6fa3
ZIG=zig@0.15.2
BINARYEN=aqua:WebAssembly/binaryen@133

root="$(cd "$(dirname "$0")/.." && pwd)"
work="$root/.tmp/zstd-wasm"
rm -rf "$work" && mkdir -p "$work"
curl -sfL "https://github.com/facebook/zstd/releases/download/v$ZSTD_VERSION/zstd-$ZSTD_VERSION.tar.gz" -o "$work/zstd.tar.gz"
echo "$ZSTD_SHA256  $work/zstd.tar.gz" | sha256sum -c --quiet
tar -xzf "$work/zstd.tar.gz" -C "$work"
lib="$work/zstd-$ZSTD_VERSION/lib"

mise exec "$ZIG" -- zig cc -target wasm32-wasi -mexec-model=reactor -O2 -flto \
  -DNDEBUG -DZSTD_LEGACY_SUPPORT=0 -DZSTD_DISABLE_ASM -DZSTD_TRACE=0 -DZSTD_NO_INTRINSICS \
  -I"$lib" -I"$lib/common" \
  "$root/packages/core/zstd/decoder.c" "$lib"/common/*.c "$lib"/decompress/*.c \
  -Wl,--export=lx_malloc,--export=lx_free,--export=lx_ddict,--export=lx_content_size,--export=lx_decode \
  -Wl,--strip-all -o "$work/decoder.wasm"

{
  echo "// Generated by scripts/build-zstd-wasm.sh from zstd $ZSTD_VERSION and packages/core/zstd/decoder.c. Do not edit."
  printf "export const ZSTD_WASM_BASE64 =\n  '%s';\n" "$(base64 -w0 "$work/decoder.wasm")"
} > "$root/packages/core/src/zstd-wasm.ts"
mise exec "$BINARYEN" -- wasm2js "$work/decoder.wasm" -Oz --enable-bulk-memory --enable-sign-ext --enable-nontrapping-float-to-int --enable-mutable-globals -o "$work/decoder.js"
{
  echo "// @ts-nocheck"
  echo "// Generated by scripts/build-zstd-wasm.sh: packages/core/zstd/decoder.c through wasm2js. Do not edit."
  sed -n '/^import \* as /!p' "$work/decoder.js" | sed '/^var retasmFunc = /,$d'
  echo "export const instantiate = (imports) => asmFunc(imports);"
} > "$root/packages/core/src/zstd-js.ts"
echo "decoder.wasm $(stat -c %s "$work/decoder.wasm") bytes, zstd-js.ts $(stat -c %s "$root/packages/core/src/zstd-js.ts") bytes"
